const defaultCareerTips = '''
# Make your CV work for you

Keep it to one or two pages. Put your most recent job first, and under each job write two or three lines about what you achieved, not just what your duties were. For example, "Reduced stock losses by keeping weekly records" says more than "Responsible for stock".

Save and send your CV as a PDF. It looks the same on every phone and computer. No PDF? Open your Profile on Vocation SL and tap "Create one from my profile".

Use a phone number and email you check every day, and make sure your voicemail works.

# Apply smarter, not just more

Read the requirements before you apply. Apply to jobs where you meet most of them, and say clearly how you meet them in your cover letter.

Write a short cover letter for each job: who you are, why this job, and one or two examples that show you can do it. Mention the job title and the company's name.

Apply early. Many employers start reviewing applications before the deadline.

# Get ready for the interview

Find out about the employer: what they do, where they work, and who they serve. Prepare two or three short stories about times you solved a problem, worked in a team or learned something quickly.

Practise answering "Tell me about yourself" in under two minutes.

Arrive 15 minutes early, dressed neatly, with copies of your CV and certificates. Switch your phone to silent.

At the end, ask a question about the job or the team. It shows you are serious about the role.

# Stay safe

A genuine employer will never ask you to pay to apply, to be interviewed, or for training, uniforms or medicals before you are hired. If anyone asks you for money, don't pay. Report the job in the app and our team will check it.

Don't share your bank details or Mobile Money PIN with anyone.

For interviews, meet at the employer's office or another public place, and tell someone where you are going.

# Keep learning

Every new skill makes you a stronger candidate. Add certificates and short courses to your profile as you complete them, and keep your skills list up to date. Employers search by skill.

Refer a company that's hiring: share your code from Profile → Refer an employer and get SLE 50 by Mobile Money when its first job goes live.
''';
