const _stdBenefits = [
  'NASSIT pension contributions',
  'Medical cover for you and your dependants',
  'Annual leave of 21 working days',
  'Paid training and professional development',
];

Job _job({
  required String id,
  required String title,
  required String company,
  required String location,
  required EmploymentType type,
  required WorkMode mode,
  required Industry industry,
  required ExperienceLevel level,
  required int? min,
  required int? max,
  required int postedDaysAgo,
  required int deadlineInDays,
  required String about,
  required String description,
  required List<String> responsibilities,
  required List<String> requirements,
  required List<String> preferred,
  required List<String> skills,
  List<String> benefits = _stdBenefits,
  int applicants = 0,
  bool featured = false,
  required DateTime now,
  int postedHoursOffset = 0,
}) =>
    Job(
      id: id,
      title: title,
      companyId: company,
      location: location,
      employmentType: type,
      workMode: mode,
      industry: industry,
      experienceLevel: level,
      salaryMin: min,
      salaryMax: max,
      postedAt: now.subtract(Duration(days: postedDaysAgo, hours: postedHoursOffset)),
      deadline: DateTime(now.year, now.month, now.day, 23, 59).add(Duration(days: deadlineInDays)),
      about: about,
      description: description,
      responsibilities: responsibilities,
      requirements: requirements,
      preferred: preferred,
      skills: skills,
      benefits: benefits,
      applicants: applicants,
      featured: featured,
    );

